_v4_networks = []   # [(vendor, ip_network)]
_v6_networks = []
for _vendor, _info in CDN_DATA.items():
    for cidr in _info.get("ipv4", []):
        try:
            _v4_networks.append((_vendor, ipaddress.ip_network(cidr, strict=False)))
        except ValueError:
            pass
    for cidr in _info.get("ipv6", []):
        try:
            _v6_networks.append((_vendor, ipaddress.ip_network(cidr, strict=False)))
        except ValueError:
            pass

# 在线动态网络缓存 (refresh 后填充, 与静态库合并查询)
_online_v4 = []   # [(vendor, ip_network)]
_online_v6 = []
ONLINE_CACHE_FILE = "cdn_ranges_online.json"


def _nets_with_online(version):
    """返回合并静态+在线的网络列表"""
    if version == 4:
        return _v4_networks + _online_v4
    return _v6_networks + _online_v6


def _parse_ip(ip):
    """解析 IP 字符串为 ip_address 对象, 失败返回 None"""
    try:
        return ipaddress.ip_address(ip.strip())
    except (ValueError, AttributeError):
        return None


def is_cdn(ip):
    """判断 IP 是否属于已知 CDN 段 (静态库 + 在线缓存合并查询)"""
    addr = _parse_ip(ip)
    if addr is None:
        return False
    nets = _nets_with_online(addr.version)
    return any(addr in net for _, net in nets)


def get_vendor(ip):
    """返回 IP 所属 CDN 厂商名 (静态+在线合并), 不属于任何 CDN 返回 None"""
    addr = _parse_ip(ip)
    if addr is None:
        return None
    nets = _nets_with_online(addr.version)
    for vendor, net in nets:
        if addr in net:
            return vendor
    return None


def filter_candidates(ips):
    """从候选 IP 列表中过滤掉所有 CDN IP, 返回疑似源站 IP 列表"""
    result = []
    for ip in ips:
        ip = ip.strip() if isinstance(ip, str) else ip
        if not ip:
            continue
        if not is_cdn(ip):
            result.append(ip)
    return result


def get_asn(ip):
    """返回 IP 所属 CDN 厂商的 ASN 列表 (非 CDN 返回空)"""
    vendor = get_vendor(ip)
    if vendor is None:
        return []
    return CDN_DATA.get(vendor, {}).get("asn", [])


