import urllib.request

ONLINE_SOURCES = {
    # 厂商 -> (类型, 来源标识)   类型: "url_text" / "url_json_path" / "asn"
    "Cloudflare": ("url_text", "https://www.cloudflare.com/ips-v4", "ipv4"),
    # Cloudflare IPv6 单独处理 (见 fetch_cloudflare_v6)
    "Amazon CloudFront": ("url_json", "https://d7uri8nf7uskq.cloudfront.net/tools/list-cloudfront-ips",
                          ("CLOUDFRONT_GLOBAL_IP_LIST", "CLOUDFRONT_REGIONAL_EDGE_IP_LIST")),
    "Fastly": ("url_text", "https://api.fastly.com/public-ip-list", "all"),  # 含 v4/v6 行
}


def _http_get(url, timeout=20):
    """轻量 HTTP GET (不依赖 requests), 返回文本或 None"""
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "cdn_tracer/5.0"})
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return resp.read().decode("utf-8", errors="ignore")
    except Exception:
        return None


def _is_valid_cidr(s):
    try:
        ipaddress.ip_network(s.strip(), strict=False)
        return True
    except (ValueError, AttributeError):
        return False


def _fetch_text_lines(url, vendor):
    """从纯文本 URL 拉取 CIDR 列表 (每行一个)"""
    text = _http_get(url)
    if not text:
        return [], []
    v4, v6 = [], []
    for line in text.splitlines():
        cidr = line.strip()
        if not cidr or cidr.startswith("#"):
            continue
        if not _is_valid_cidr(cidr):
            continue
        net = ipaddress.ip_network(cidr, strict=False)
        (v4 if net.version == 4 else v6).append((vendor, net))
    return v4, v6


def _fetch_cloudflare():
    """Cloudflare IPv4 + IPv6 官方源"""
    v4 = _fetch_text_lines("https://www.cloudflare.com/ips-v4", "Cloudflare")[0]
    v6 = _fetch_text_lines("https://www.cloudflare.com/ips-v6", "Cloudflare")[1]
    return v4, v6


def _fetch_aws_cloudfront():
    """AWS CloudFront 官方 JSON"""
    text = _http_get("https://d7uri8nf7uskq.cloudfront.net/tools/list-cloudfront-ips")
    v4, v6 = [], []
    if not text:
        return v4, v6
    try:
        data = json.loads(text)
    except Exception:
        return v4, v6
    for key in ("CLOUDFRONT_GLOBAL_IP_LIST", "CLOUDFRONT_REGIONAL_EDGE_IP_LIST"):
        for cidr in data.get(key, []):
            if not _is_valid_cidr(cidr):
                continue
            net = ipaddress.ip_network(cidr, strict=False)
            (v4 if net.version == 4 else v6).append(("Amazon CloudFront", net))
    return v4, v6


def _fetch_fastly():
    """Fastly 官方 (IPv4+IPv6 混合文本)"""
    return _fetch_text_lines("https://api.fastly.com/public-ip-list", "Fastly")


def _fetch_azure_frontdoor():
    """Azure Front Door / CDN ServiceTags (从官方 JSON 过滤 FrontDoor/Cdn 标签)"""
    text = _http_get("https://download.microsoft.com/download/7/1/D/71D86715-5596-4529-9B13-DA13A5DE5B63/ServiceTags_Public_20250101.json",
                     timeout=40)
    v4, v6 = [], []
    if not text:
        return v4, v6
    try:
        data = json.loads(text)
    except Exception:
        return v4, v6
    for tag in data.get("values", []):
        name = (tag.get("id") or "").lower()
        if "frontdoor" in name or tag.get("name", "").startswith("AzureFrontDoor"):
            for cidr in tag.get("properties", {}).get("addressPrefixes", []):
                if not _is_valid_cidr(cidr):
                    continue
                net = ipaddress.ip_network(cidr, strict=False)
                (v4 if net.version == 4 else v6).append(("Azure Front Door", net))
    return v4, v6


def _fetch_by_asn(asn, vendor, timeout=20):
    """按 ASN 从 bgpview API 拉取全部前缀 (IPv4+IPv6)"""
    asn_num = str(asn).lstrip("ASasAS")
    url = f"https://api.bgpview.io/asn/{asn_num}/prefixes"
    text = _http_get(url, timeout=timeout)
    v4, v6 = [], []
    if not text:
        return v4, v6
    try:
        data = json.loads(text)
    except Exception:
        return v4, v6
    for item in data.get("data", {}).get("ipv4_prefixes", []):
        cidr = item.get("prefix")
        if cidr and _is_valid_cidr(cidr):
            v4.append((vendor, ipaddress.ip_network(cidr, strict=False)))
    for item in data.get("data", {}).get("ipv6_prefixes", []):
        cidr = item.get("prefix")
        if cidr and _is_valid_cidr(cidr):
            v6.append((vendor, ipaddress.ip_network(cidr, strict=False)))
    return v4, v6


def fetch_online(vendors=None, use_asn=True, timeout=20):
    """并发拉取在线源, 返回 (v4_list, v6_list, report_dict)
    vendors: None=全部有官方源/ASN的厂商; 或指定列表
    use_asn: 是否对有 ASN 的厂商按 ASN 补充拉取 (覆盖官方源未列的厂商)"""
    import concurrent.futures

    # 官方源任务 (最准)
    official_jobs = {
        "Cloudflare": _fetch_cloudflare,
        "Amazon CloudFront": _fetch_aws_cloudfront,
        "Fastly": _fetch_fastly,
        "Azure Front Door": _fetch_azure_frontdoor,
    }
    if vendors is not None:
        official_jobs = {k: v for k, v in official_jobs.items() if k in vendors}

    v4_all, v6_all = [], []
    report = {}

    log_fn = print
    log_fn("[在线拉取] 启动官方源拉取...")
    with concurrent.futures.ThreadPoolExecutor(max_workers=8) as ex:
        futures = {ex.submit(fn): name for name, fn in official_jobs.items()}
        for fut in concurrent.futures.as_completed(futures):
            name = futures[fut]
            try:
                v4, v6 = fut.result()
                v4_all.extend(v4); v6_all.extend(v6)
                report[name] = {"v4": len(v4), "v6": len(v6), "source": "official"}
                log_fn(f"  [官方] {name}: +{len(v4)} v4 / +{len(v6)} v6")
            except Exception as e:
                report[name] = {"error": str(e)[:60]}
                log_fn(f"  [官方] {name}: 失败 {e}")

    # 按 ASN 补充 (覆盖官方源未覆盖的厂商)
    if use_asn:
        targets = vendors if vendors is not None else list(CDN_DATA.keys())
        asn_jobs = {}
        for v in targets:
            for asn in CDN_DATA.get(v, {}).get("asn", []):
                # 已有官方源的厂商也补 ASN (官方源可能不完整)
                asn_jobs[(v, asn)] = (asn, v)
        if asn_jobs:
            log_fn(f"[在线拉取] 按 ASN 拉取 {len(asn_jobs)} 个 ASN...")
            with concurrent.futures.ThreadPoolExecutor(max_workers=6) as ex:
                futures = {ex.submit(_fetch_by_asn, asn, v): (v, asn)
                           for (v, asn), (asn, v) in asn_jobs.items()}
                for fut in concurrent.futures.as_completed(futures):
                    v, asn = futures[fut]
                    try:
                        v4, v6 = fut.result()
                        v4_all.extend(v4); v6_all.extend(v6)
                        key = f"{v} ({asn})"
                        report[key] = {"v4": len(v4), "v6": len(v6), "source": "asn"}
                    except Exception as e:
                        report[f"{v} ({asn})"] = {"error": str(e)[:60]}

    # 去重 (同 vendor+网络 保留一个)
    seen4, seen6 = set(), set()
    dedup_v4, dedup_v6 = [], []
    for vendor, net in v4_all:
        k = (vendor, str(net))
        if k not in seen4:
            seen4.add(k); dedup_v4.append((vendor, net))
    for vendor, net in v6_all:
        k = (vendor, str(net))
        if k not in seen6:
            seen6.add(k); dedup_v6.append((vendor, net))
    log_fn(f"[在线拉取] 去重后: {len(dedup_v4)} v4 / {len(dedup_v6)} v6")
    return dedup_v4, dedup_v6, report


def refresh(vendors=None, save=True, use_asn=True):
    """拉取在线源, 合并到模块级缓存 (_online_v4/_online_v6), 可选保存 JSON 缓存。
    返回统计 dict。调用后 is_cdn/get_vendor/filter_candidates 自动包含在线数据。"""
    global _online_v4, _online_v6
    v4, v6, report = fetch_online(vendors=vendors, use_asn=use_asn)
    _online_v4 = v4
    _online_v6 = v6
    result = {
        "online_v4": len(v4), "online_v6": len(v6),
        "static_v4": len(_v4_networks), "static_v6": len(_v6_networks),
        "total_v4": len(v4) + len(_v4_networks),
        "total_v6": len(v6) + len(_v6_networks),
        "report": report,
    }
    if save:
        try:
            payload = {
                "fetched_at": datetime.now().isoformat(),
                "vendors": {
                    v: {"ipv4": [str(n) for vv, n in v4 if vv == v],
                        "ipv6": [str(n) for vv, n in v6 if vv == v]}
                    for v in {vv for vv, _ in v4 + v6}
                },
            }
            Path(ONLINE_CACHE_FILE).write_text(json.dumps(payload, indent=2, ensure_ascii=False))
        except Exception:
            pass
    return result


def load_online_cache(path=None):
    """从 refresh 保存的 JSON 缓存加载在线段 (离线场景用, 免再次联网)"""
    global _online_v4, _online_v6
    path = path or ONLINE_CACHE_FILE
    try:
        data = json.loads(Path(path).read_text())
    except Exception:
        return False
    v4, v6 = [], []
    for vendor, info in data.get("vendors", {}).items():
        for cidr in info.get("ipv4", []):
            if _is_valid_cidr(cidr):
                v4.append((vendor, ipaddress.ip_network(cidr, strict=False)))
        for cidr in info.get("ipv6", []):
            if _is_valid_cidr(cidr):
                v6.append((vendor, ipaddress.ip_network(cidr, strict=False)))
    _online_v4, _online_v6 = v4, v6
    return True


def load_online_full(path):
    """从 cdn_ip_collector.py 输出的 JSON 加载 (cdn_ranges_full.json)
    格式: {"meta":..., "vendors": {vendor: {"v4": [...], "v6": [...]}}}
    返回 True/False"""
    global _online_v4, _online_v6
    try:
        data = json.loads(Path(path).read_text())
    except Exception:
        return False
    v4, v6 = [], []
    for vendor, info in data.get("vendors", {}).items():
        for cidr in info.get("v4", []):
            if _is_valid_cidr(cidr):
                v4.append((vendor, ipaddress.ip_network(cidr, strict=False)))
        for cidr in info.get("v6", []):
            if _is_valid_cidr(cidr):
                v6.append((vendor, ipaddress.ip_network(cidr, strict=False)))
    _online_v4, _online_v6 = v4, v6
    return True


def build_all():
    """导出全部数据库为 dict (供 JSON 持久化/外部工具消费)"""
    return {
        vendor: {"asn": info["asn"], "ipv4": info["ipv4"], "ipv6": info["ipv6"]}
        for vendor, info in CDN_DATA.items()
    }


